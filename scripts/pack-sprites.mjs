import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
process.chdir(fileURLToPath(new URL("..", import.meta.url)));
const inventory = JSON.parse(readFileSync("art/generation.json", "utf8"));
const run = (bin, args) => execFileSync(bin, args, { encoding: "utf8" });
const font =
  process.env.SPRITE_CATALOG_FONT ??
  (existsSync("/System/Library/Fonts/Supplemental/Arial.ttf")
    ? "/System/Library/Fonts/Supplemental/Arial.ttf"
    : "DejaVu-Sans");
mkdirSync("output/art", { recursive: true });
mkdirSync("src/game/assets", { recursive: true });
const images = inventory.atlasKeys.map((key) => `art/sprites/${key}.png`);
for (const image of images) {
  const size = run("magick", [image, "-format", "%wx%h", "info:"]);
  if (size !== "256x256") throw Error(`Unexpected sprite frame: ${image}`);
}
run("magick", [
  "montage",
  "-font",
  font,
  ...images,
  "-tile",
  "4x",
  "-geometry",
  "256x256+0+0",
  "-background",
  "none",
  "-strip",
  "output/art/dungeon-atlas.png",
]);
run("cwebp", [
  "-quiet",
  "-q",
  "88",
  "-alpha_q",
  "100",
  "-m",
  "6",
  "output/art/dungeon-atlas.png",
  "-o",
  "src/game/assets/dungeon-atlas.webp",
]);
run("cwebp", [
  "-quiet",
  "-q",
  "88",
  "art/sprites/dungeon-floor.png",
  "-o",
  "src/game/assets/dungeon-floor.webp",
]);
writeFileSync(
  "src/game/sprite-keys.ts",
  `// Atlas order from art/generation.json. Generated by scripts/pack-sprites.mjs.\nexport const DUNGEON_SPRITES = [\n${inventory.atlasKeys.map((key) => `  "${key}",`).join("\n")}\n] as const;\nexport type DungeonSpriteKey = (typeof DUNGEON_SPRITES)[number];\n`,
);
console.log(
  `Packed ${images.length} sprites and the floor background. Builds consume the prepared files.`,
);
